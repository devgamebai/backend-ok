    /**
     * Replay 3 raw production-shape payloads (sign+request_time as
     * actually emitted by GSC) and verify the parser doesn't choke or
     * crash. The captured signs predictably won't validate against
     * {@link #TEST_SECRET} so the aggregator returns the
     * SIGNATURE_ERROR shape — verifying the no-crash invariant + the
     * legacy {@code "Invalid sign"} response shape.
     *
     * <p>Note: production {@code gsc_event_log} rows for the
     * {@code "pushbet"} endpoint may be sparse or absent depending on
     * traffic mix (PushBet is the lowest-TPS GSC endpoint). The
     * payloads below are synthetic but match the documented GSC
     * provider schema — sufficient to exercise the parser surface.
     */
    @Test
    public void productionPayloadsParseWithoutThrowing() throws Exception {
        String[] payloads = {
                "{\"sign\":\"99d8185c4d7c3939bc9c232fc383b0da\",\"currency\":\"KRW\",\"request_time\":\"1777706702\",\"operator_code\":\"G7A1\",\"transactions\":[{\"id\":\"PROD-1\",\"action\":\"BET\",\"member_account\":\"khongduong\",\"product_code\":1002,\"amount\":\"5000\",\"wager_code\":\"WPROD-1\"}]}",
                "{\"sign\":\"36e5bfd072b758d07a7ceb503d31d505\",\"currency\":\"VND\",\"request_time\":\"1777696496\",\"operator_code\":\"G7A1\",\"wagers\":[{\"id\":\"PROD-2\",\"action\":\"BET\",\"member_account\":\"sunkrvip999\",\"product_code\":1091,\"bet_amount\":\"100000\",\"wager_code\":\"WPROD-2\"}]}",
                "{\"sign\":\"2a676c3c6c7f890f82847a9beb4e5502\",\"currency\":\"KRW\",\"request_time\":\"1777705550\",\"operator_code\":\"G7A1\",\"transactions\":[{\"id\":\"PROD-3\",\"action\":\"BET\",\"member_account\":\"hayquamnoi\",\"product_code\":1002,\"amount\":\"250\",\"wager_code\":\"WPROD-3\"}]}"
        };
        for (String body : payloads) {
            String resp = aggregator.handle(mockRequest(body));
            assertNotNull(resp);
            JSONObject obj = new JSONObject(resp);
            // Prod sign won't match the TEST_SECRET → SIGNATURE_ERROR
            // path → legacy "Invalid sign" shape.
            assertEquals("Invalid sign", obj.optString("message"));
            assertEquals(1, obj.optInt("code"));
        }
    }

