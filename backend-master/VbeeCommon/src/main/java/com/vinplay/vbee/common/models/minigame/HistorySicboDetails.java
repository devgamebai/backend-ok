package com.vinplay.vbee.common.models.minigame;

public class HistorySicboDetails {
    private String slot;
    private long referenceId;
    private long bet;
    private long win;

    public String getSlot() { return slot; }
    public void setSlot(String slot) { this.slot = slot; }
    public long getReferenceId() { return referenceId; }
    public void setReferenceId(long referenceId) { this.referenceId = referenceId; }
    public long getBet() { return bet; }
    public void setBet(long bet) { this.bet = bet; }
    public long getWin() { return win; }
    public void setWin(long win) { this.win = win; }
}
